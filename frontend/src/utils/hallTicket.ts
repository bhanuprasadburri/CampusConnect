import { Exam } from '../data/exams';

interface HallTicketStudent {
  fullName: string;
  rollNo: string;
  department: string;
  program: string;
  semester: number;
}

const pdfSafe = (value: string | number) => String(value)
  .normalize('NFKD')
  .replace(/[^\x20-\x7E]/g, '?')
  .replace(/([\\()])/g, '\\$1');

export const downloadHallTicketPdf = (student: HallTicketStudent, exams: Exam[]) => {
  const commands: string[] = [];
  const text = (x: number, y: number, value: string | number, size = 10, font = 'F1') => {
    commands.push(`BT /${font} ${size} Tf ${x} ${y} Td (${pdfSafe(value)}) Tj ET`);
  };

  text(45, 750, 'CampusConnect', 21, 'F2');
  text(45, 724, 'EXAMINATION HALL TICKET', 14, 'F2');
  text(45, 700, 'Candidate details and examination schedule', 9);
  commands.push('45 688 m 567 688 l S');
  text(45, 666, `Student: ${student.fullName}`, 10, 'F2');
  text(360, 666, `Roll No: ${student.rollNo}`, 10, 'F2');
  text(45, 646, `Program: ${student.program}`);
  text(360, 646, `Department: ${student.department}`);
  text(45, 626, `Semester: ${student.semester}`);
  text(360, 626, `Academic Year: ${exams[0]?.date.getFullYear() ?? new Date().getFullYear()} - ${(exams[0]?.date.getFullYear() ?? new Date().getFullYear()) + 1}`);
  commands.push('45 606 m 567 606 l S');
  text(45, 584, 'DATE', 9, 'F2');
  text(135, 584, 'TIME', 9, 'F2');
  text(260, 584, 'SUBJECT', 9, 'F2');
  text(455, 584, 'ROOM / SEAT', 9, 'F2');

  exams.forEach((exam, index) => {
    const y = 558 - index * 34;
    text(45, y, exam.date.toLocaleDateString('en-US', { day: '2-digit', month: 'short', year: 'numeric' }), 8);
    text(135, y, `${exam.start} - ${exam.end}`, 8);
    text(260, y, `${exam.code} ${exam.subject}`.slice(0, 32), 8);
    text(455, y, `${exam.room} / ${exam.seat}`.slice(0, 18), 7);
  });

  commands.push('45 370 m 567 370 l S');
  text(45, 346, 'Candidate instructions', 11, 'F2');
  text(45, 324, '1. Bring this hall ticket and your valid college identity card.', 9);
  text(45, 306, '2. Report to the examination room at least 30 minutes before the exam.', 9);
  text(45, 288, '3. Follow all instructions provided by the examination supervisor.', 9);
  text(45, 92, 'This hall ticket was generated by CampusConnect.', 8);

  const content = commands.join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 6 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach((offset) => { pdf += `${String(offset).padStart(10, '0')} 00000 n \n`; });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  const url = URL.createObjectURL(new Blob([pdf], { type: 'application/pdf' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = `CampusConnect_Hall_Ticket_${student.rollNo.replace(/[^a-zA-Z0-9_-]/g, '_')}.pdf`;
  link.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
};
